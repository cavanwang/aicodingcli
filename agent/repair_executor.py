"""基础版自动修复执行器。

当错误自愈识别出特定问题类型时，尝试自动执行一轮最小修复。
当前先支持：
- 依赖缺失：根据报错中的模块名向 requirements.txt 中补入依赖
- 语法错误：优先在报错引用的目标文件上创建占位内容
- 文件缺失：根据报错中的目标路径创建对应文件，便于后续修复
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

import config
from agent.tools.file_ops import list_directory, write_file


def execute_repair(classification: dict[str, Any]) -> str:
    """执行基础修复动作，优先做最小且安全的处理。"""
    error_type = classification.get("error_type", "unknown")

    if error_type == "dependency":
        return _repair_dependency(classification)

    if error_type == "syntax":
        return _repair_syntax(classification)

    if error_type == "file_not_found":
        return _repair_file_not_found(classification)

    return "未匹配到可自动修复的策略。"


def _repair_dependency(classification: dict[str, Any]) -> str:
    """针对依赖缺失，向 requirements.txt 中补入模块，并为报错行所在的 Python 文件添加安全兜底导入。"""
    details = classification.get("details", "")
    module_name = _extract_dependency_module(details)
    # 优先使用分类器提取的结构化字段
    target_path = classification.get("file_path") or _extract_target_path(details)
    target_line = classification.get("line_number") or _extract_line_number(details)

    requirements_path = "requirements.txt"
    requirements_file = config.WORKSPACE_DIR / requirements_path
    patch_result = ""

    if module_name:
        if requirements_file.exists():
            existing = requirements_file.read_text(encoding="utf-8")
            if re.search(
                rf"(^|\s){re.escape(module_name)}([<>=!~].*)?$",
                existing,
                re.MULTILINE,
            ):
                patch_result = (
                    f"依赖文件已存在：requirements.txt，且已包含 {module_name}。"
                )
            else:
                content = (
                    existing.rstrip()
                    + ("\n" if existing.strip() else "")
                    + f"{module_name}\n"
                )
                write_result = write_file(requirements_path, content)
                patch_result = f"{write_result}\n已向 requirements.txt 中加入缺失依赖：{module_name}"
        else:
            content = f"# Auto-generated by error recovery executor\n{module_name}\n"
            write_result = write_file(requirements_path, content)
            patch_result = (
                f"{write_result}\n已向 requirements.txt 中加入缺失依赖：{module_name}"
            )

        if target_path:
            target_file = _resolve_workspace_path(target_path)
            if target_file.exists() and target_file.suffix == ".py":
                file_patch = _patch_python_import_fallback(
                    target_file,
                    module_name,
                    target_line=target_line,
                )
                if file_patch:
                    patch_result = f"{patch_result}\n{file_patch}"
        else:
            for candidate in sorted(config.WORKSPACE_DIR.rglob("*.py")):
                if candidate.is_file() and ".venv" not in candidate.parts:
                    file_patch = _patch_python_import_fallback(
                        candidate,
                        module_name,
                        target_line=target_line,
                    )
                    if file_patch:
                        patch_result = f"{patch_result}\n{file_patch}"
                        break

        return patch_result or "未能从错误输出中解析出缺失模块名。"

    return "未能从错误输出中解析出缺失模块名。"


def _repair_syntax(classification: dict[str, Any]) -> str:
    """语法错误时，优先在报错引用的目标文件上创建占位内容。"""
    details = classification.get("details", "")
    target_path = classification.get("file_path") or _extract_target_path(details)
    if target_path:
        target_file = config.WORKSPACE_DIR / target_path
        if target_file.exists():
            return f"目标文件已存在：{target_path}，未覆盖原文件。"

        content = (
            "# Auto-generated by error recovery executor\n"
            "# Placeholder created for syntax recovery.\n"
            f"# Original error: {details}\n"
        )
        write_result = write_file(target_path, content)
        return f"{write_result}\n已根据语法报错路径创建目标文件：{target_path}"

    content = (
        "# Auto-generated by error recovery executor\n"
        f"# Original error: {details}\n"
        "\n"
        "# Please fix the syntax issue in the relevant source file.\n"
    )
    write_result = write_file(".aicoding_recovery/syntax_recovery.py", content)
    return f"{write_result}\n已创建语法修复占位文件。"


def _repair_file_not_found(classification: dict[str, Any]) -> str:
    """文件缺失时，优先在报错提到的目标路径创建缺失文件。"""
    details = classification.get("details", "")
    target_path = classification.get("file_path") or _extract_target_path(details)
    if target_path:
        target_file = config.WORKSPACE_DIR / target_path
        if target_file.exists():
            return f"目标文件已存在：{target_path}，未覆盖原文件。"

        if target_file.suffix == ".py":
            content = (
                '"""Auto-generated stub module for missing file."""\n'
                "\n"
                "def main() -> None:\n"
                '    """Placeholder implementation created by the recovery executor."""\n'
                "    pass\n"
            )
        else:
            content = (
                "# Auto-generated by error recovery executor\n"
                f"# Original error: {details}\n"
            )
        write_result = write_file(target_path, content)
        return f"{write_result}\n已根据缺失文件路径创建目标文件：{target_path}"

    try:
        listing = list_directory(".")
    except Exception as exc:  # pragma: no cover - defensive fallback
        listing = f"列目录失败: {exc}"

    content = (
        "# 文件缺失修复说明\n"
        "# 该文件由错误自愈执行器自动生成。\n"
        f"# 原始错误: {details}\n"
        "\n"
        "请确认目标文件是否存在，并修正路径。"
    )
    note_result = write_file(".aicoding_recovery/file_missing_note.md", content)

    return (
        f"{note_result}\n"
        "文件缺失修复说明已生成。"
        "检测到文件或路径问题，请先确认目标文件是否存在。"
        f"\n工作区文件列表:\n{listing}"
    )


def _extract_dependency_module(details: str) -> str | None:
    match = re.search(
        r"no module named ['\"]?([A-Za-z0-9_.-]+)['\"]?",
        details,
        re.IGNORECASE,
    )
    if match:
        return match.group(1)
    return None


def _extract_target_path(details: str) -> str | None:
    match = re.search(
        r"['\"]([A-Za-z0-9_./\\-]+\.(?:py|md|txt|json|yaml|yml|toml|ini|cfg|sh))['\"]",
        details,
    )
    if match:
        return match.group(1)
    return None


def _find_import_insert_position(content: str) -> int:
    """找到插入导入块的正确位置（在 docstring 和 from __future__ 之后）。

    返回行号（0-indexed），表示应在此行之前插入。
    """
    lines = content.splitlines(keepends=True)
    if not lines:
        return 0

    pos = 0

    # 跳过开头的空行和注释
    while pos < len(lines) and (lines[pos].strip() == "" or lines[pos].strip().startswith("#")):
        pos += 1

    # 跳过模块 docstring（""" 或 '''）
    if pos < len(lines):
        stripped = lines[pos].strip()
        if stripped.startswith('"""') or stripped.startswith("'''"):
            quote = stripped[:3]
            # 单行 docstring
            if stripped.count(quote) >= 2 and len(stripped) > 3:
                pos += 1
            else:
                # 多行 docstring，找到结束标记
                pos += 1
                while pos < len(lines):
                    if quote in lines[pos]:
                        pos += 1
                        break
                    pos += 1

    # 跳过 from __future__ 导入
    while pos < len(lines):
        stripped = lines[pos].strip()
        if stripped == "" or stripped.startswith("#"):
            pos += 1
            continue
        if stripped.startswith("from __future__"):
            pos += 1
            continue
        break

    return pos


def _patch_python_import_fallback(
    path: Path,
    module_name: str,
    *,
    target_line: int | None = None,
) -> str | None:
    """为现有 Python 文件添加一个受保护的导入兜底；当给出行号时，优先修改对应行。"""
    content = path.read_text(encoding="utf-8")
    if not content.strip():
        content = ""

    alias = _module_alias(module_name)

    if target_line is not None:
        lines = content.splitlines()
        if 1 <= target_line <= len(lines):
            target_text = lines[target_line - 1].strip()
            if target_text.startswith("import ") or target_text.startswith("from "):
                replacement = (
                    f"try:\n"
                    f"    {target_text}\n"
                    f"except ImportError:  # pragma: no cover - optional dependency fallback\n"
                    f"    {alias} = None\n"
                )
                lines[target_line - 1] = replacement
                new_content = "\n".join(lines)
                path.write_text(new_content, encoding="utf-8")
                try:
                    display_path = path.relative_to(config.WORKSPACE_DIR)
                except ValueError:
                    display_path = path.name
                return f"已在 {display_path} 的第 {target_line} 行做导入兜底修复"

    if re.search(
        rf"\bimport\s+{re.escape(module_name)}\b|\bfrom\s+{re.escape(module_name)}\b",
        content,
    ):
        return None

    import_block = (
        f"# Auto-generated fallback for optional dependency: {module_name}\n"
        f"try:\n"
        f"    import {module_name} as {alias}\n"
        f"except ImportError:  # pragma: no cover - optional dependency fallback\n"
        f"    {alias} = None\n\n"
    )

    # 找到正确的插入位置：在 docstring 和 from __future__ 之后
    insert_pos = _find_import_insert_position(content)
    lines = content.splitlines(keepends=True)
    new_content = "".join(lines[:insert_pos]) + import_block + "".join(lines[insert_pos:])
    path.write_text(new_content, encoding="utf-8")
    return f"已为 Python 文件补丁导入兜底：{path.relative_to(config.WORKSPACE_DIR)}"


def _module_alias(module_name: str) -> str:
    alias = re.sub(r"[^0-9a-zA-Z]+", "_", module_name).strip("_")
    return alias or "module"


def _resolve_workspace_path(target_path: str | Path) -> Path:
    path = Path(target_path)
    if path.is_absolute():
        return path.resolve()
    workspace = config.WORKSPACE_DIR.resolve()
    resolved = (workspace / path).resolve()
    if not str(resolved).startswith(str(workspace)):
        raise PermissionError(f"路径越界: {target_path}")
    return resolved


def _extract_line_number(details: str) -> int | None:
    match = re.search(r"line\s+(\d+)", details, re.IGNORECASE)
    if match:
        return int(match.group(1))
    return None
